  const DICTS = { es, en };

  function resolveLang(pref, systemLocale) {
    if (pref && pref !== 'auto' && DICTS[pref]) return pref;
    const l = String(systemLocale || 'es').toLowerCase();
    return l.startsWith('es') || l.startsWith('ca') || l.startsWith('gl') || l.startsWith('eu') ? 'es' : 'en';
  }

  function make(lang) {
    const d = DICTS[lang] || es;
    const t = (key, vars) => {
      let s = d[key];
      if (s === undefined) s = es[key];
      if (s === undefined) return key;
      if (vars && typeof s === 'string') {
        s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
      }
      return s;
    };
    t.lang = lang;
    t.raw = (key) => d[key];
    return t;
  }

  return { make, resolveLang, DICTS };
